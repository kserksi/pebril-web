async function setup(viewport, reducedMotion = 'no-preference', hasTouch = false) {
  const page = await browser.newPage({ viewport, reducedMotion, hasTouch });
  page.on('pageerror', error => errors.push(error.message));
  await page.route('https://**/*', route => route.abort());
  await page.addInitScript(() => {
    window.localUrls = []; window.releasedUrls = []; window.storageWrites = [];
    const create = URL.createObjectURL.bind(URL), revoke = URL.revokeObjectURL.bind(URL);
    URL.createObjectURL = blob => { const url = create(blob); window.localUrls.push(url); return url; };
    URL.revokeObjectURL = url => { window.releasedUrls.push(url); revoke(url); };
    const set = Storage.prototype.setItem;
    Storage.prototype.setItem = function(...args) { window.storageWrites.push(args[0]); return set.apply(this,args); };
  });
  await page.clock.install();
  await page.goto(url);
  await page.waitForFunction(() => document.documentElement.dataset.state === 'idle');
  await page.clock.pauseAt(await page.evaluate(() => Date.now() + 100));
  return page;
}
